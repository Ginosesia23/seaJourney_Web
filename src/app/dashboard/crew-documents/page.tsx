                    start_date: testimonial.start_date,
                    end_date: testimonial.end_date,
                    total_days: testimonial.total_days,
                    at_sea_days: testimonial.at_sea_days,
                    standby_days: testimonial.standby_days,
                    yard_days: testimonial.yard_days,
